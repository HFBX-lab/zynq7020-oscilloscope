"""Generate a deterministic 256-entry, signed pixel-offset LUT (not an ADC source)."""
from pathlib import Path
import math

out=Path(__file__).resolve().parents[1]/'hardware/rtl/lcd_sine_rom.v'
lines=['`timescale 1ns/1ps', '// Generated by scripts/generate_sine_rom.py: 120 * sin(2*pi*i/256).',
       'module lcd_sine_rom(input wire [7:0] address, output reg signed [8:0] value);',
       '  always @* begin', '    case(address)']
for i in range(256):
    v=round(120*math.sin(2*math.pi*i/256))
    literal=f"-9'sd{-v}" if v<0 else f"9'sd{v}"
    lines.append(f"      8'd{i}:value={literal};")
lines+=['      default:value=0;', '    endcase', '  end', 'endmodule', '']
out.write_text('\n'.join(lines),encoding='utf-8')
print('Generated',out.name)
